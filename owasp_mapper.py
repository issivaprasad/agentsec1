import re as _re
_AH_CAT_RE = _re.compile(r'agentharm[^(]*\(([A-Z]+)\)')

def _violation_to_owasp_ids(violation: str) -> list[str]:
    """Map a single violation string to OWASP ASI IDs."""
    # Handle real violation formats generated by the monitors

    # agentharm:tool(CAT) → agentharm_CAT
    m = _AH_CAT_RE.search(violation)
    if m and violation.startswith("agentharm"):
        cat_key = f"agentharm_{m.group(1)}"
        if cat_key in _VIOLATION_TO_OWASP:
            return _VIOLATION_TO_OWASP[cat_key]

    # action_not_in_whitelist:tool → whitelist_violation
    if violation.startswith("action_not_in_whitelist"):
        return _VIOLATION_TO_OWASP.get("whitelist_violation", ["ASI-02"])

    # velocity:N/Ws → velocity_exceeded
    if violation.startswith("velocity"):
        return _VIOLATION_TO_OWASP.get("velocity_exceeded", ["ASI-07"])

    # sustained_anomaly → behaviour drift
    if violation.startswith("sustained_anomaly"):
        return ["ASI-06"]

    # Direct prefix match (longest-first for specificity)
    for prefix in sorted(_VIOLATION_TO_OWASP, key=len, reverse=True):
        if violation.startswith(prefix):
            return _VIOLATION_TO_OWASP[prefix]
    return []


class OWASPRiskMapper:
    """
    Two-step OWASP ASI Risk Mapper.

    Step 1 — Calculate risk score R from B and P scores:
        R = max(B, P)
        Risk score is derived from the detection stage outputs FIRST,
        before any OWASP category mapping occurs.

    Step 2 — Map violations to OWASP ASI Top 10 categories:
        Violation strings → OWASP IDs → category labels and weights.
        The pre-calculated R is returned alongside category metadata.

    Rationale for two-step order:
        Risk is a property of what was detected (B and P scores).
        OWASP categories are labels that describe the TYPE of risk —
        they annotate the risk score but do not determine its magnitude.
        This ensures R is grounded in the detection evidence before
        the taxonomy classification step.
    """

    @staticmethod
    def calculate_risk(B: float, P: float) -> float:
        """
        Step 1: Calculate risk score R from behaviour and policy scores.

        R = max(B, P)

        The maximum operator is used because any single confirmed
        detection (either behavioural sequence anomaly OR policy
        violation) is sufficient to establish risk at that severity
        level. Using max ensures the highest detected signal sets
        the risk score without diluting it by unrelated clean scores.

        Args:
            B: Behavioural anomaly score from behaviour_monitor [0,1]
            P: Policy severity score from policy_monitor        [0,1]

        Returns:
            R: Risk score [0,1]
        """
        B = max(0.0, min(1.0, float(B)))
        P = max(0.0, min(1.0, float(P)))
        return round(max(B, P), 4)

    def map(self, violations: list[str], behavioural_score: float,
            policy_owasp_ids: list[str] | None = None,
            risk_score: float | None = None) -> dict:
        """
        Step 2: Map violations to OWASP ASI Top 10 categories.

        Args:
            violations:          Violation strings from all monitors
            behavioural_score:   B score (used for drift category)
            policy_owasp_ids: OWASP IDs from policy (optional)
            risk_score:          Pre-calculated R from calculate_risk()
                                 If None, falls back to category-weight max

        Returns:
            {
              category_ids:     [...],
              owasp_categories: [{id, name, weight}, ...],
              risk_score:       float,   ← pre-calculated R (Step 1)
              risk_level:       str,
            }
        """
        matched: set[str] = set()

        # Map each violation string to OWASP categories
        for v in violations:
            matched.update(_violation_to_owasp_ids(v))

        # Behavioural score → behaviour drift category
        if behavioural_score >= 0.80:
            matched.update(["ASI-01"])
        elif behavioural_score >= 0.50:
            matched.add("ASI-01")

        # Direct merge from policy
        if policy_owasp_ids:
            matched.update(policy_owasp_ids)

        category_ids = sorted(matched)
        categories   = [
            {
                "id":     cid,
                "name":   OWASP_ASI[cid]["name"],
                "weight": OWASP_ASI[cid]["weight"],
            }
            for cid in category_ids
            if cid in OWASP_ASI
        ]

        # Use pre-calculated R if provided (Step 1 output),
        # otherwise fall back to max category weight
        if risk_score is not None:
            final_risk = round(float(risk_score), 4)
        else:
            final_risk = max((c["weight"] for c in categories), default=0.0)
            final_risk = max(final_risk, round(behavioural_score * 0.5, 3))

        risk_level = next(
            (l for t, l in RISK_LEVELS if final_risk >= t), "Low"
        )

        return {
            "category_ids":     category_ids,
            "owasp_categories": categories,
            "risk_score":       final_risk,
            "risk_level":       risk_level,
        }
